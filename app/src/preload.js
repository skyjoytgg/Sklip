// Expose à l'interface une API limitée et sûre (window.sklip).
const { contextBridge, ipcRenderer } = require('electron');

const on = (channel) => (cb) => {
  const handler = (_e, payload) => cb(payload);
  ipcRenderer.on(channel, handler);
  return () => ipcRenderer.removeListener(channel, handler);
};

contextBridge.exposeInMainWorld('sklip', {
  getSettings: () => ipcRenderer.invoke('settings:get'),
  updateSettings: (patch) => ipcRenderer.invoke('settings:update', patch),
  engine: (command, params) => ipcRenderer.invoke('engine:run', command, params),
  listStreams: () => ipcRenderer.invoke('streams:list'),
  journalList: () => ipcRenderer.invoke('journal:list'),
  journalGet: (id) => ipcRenderer.invoke('journal:get', id),
  onJournal: on('journal:update'),
  obsScenes: () => ipcRenderer.invoke('obs:scenes'),
  livesList: () => ipcRenderer.invoke('lives:list'),
  liveGet: (folder) => ipcRenderer.invoke('lives:get', folder),
  liveThumb: (folder) => ipcRenderer.invoke('lives:thumb', folder),
  openVideo: () => ipcRenderer.invoke('dialog:openVideo'),
  bugReport: () => ipcRenderer.invoke('log:report'),
  openLogs: () => ipcRenderer.invoke('log:openFolder'),
  analyzeVideo: (video) => ipcRenderer.invoke('analysis:start', video),
  analysisStatus: () => ipcRenderer.invoke('analysis:status'),
  reanalyze: (folder) => ipcRenderer.invoke('analysis:again', folder),
  editorSession: (folder, theme) => ipcRenderer.invoke('session:editor', folder, theme),
  onAnalysisState: on('analysis:state'),
  onAnalysisDone: on('analysis:done'),
  addMarker: () => ipcRenderer.invoke('marker:add'),
  markerHotkeyOk: () => ipcRenderer.invoke('marker:hotkeyOk'),
  onMarker: on('marker:added'),
  saveProject: (folder, theme, project) => ipcRenderer.invoke('project:save', folder, theme, project),
  saveSticker: (folder, name, dataUrl) => ipcRenderer.invoke('sticker:save', folder, name, dataUrl),
  agentsList: () => ipcRenderer.invoke('agents:list'),
  agentPortrait: (uuid) => ipcRenderer.invoke('agents:portrait', uuid),
  testPc: () => ipcRenderer.invoke('system:test'),
  openFolder: (p) => ipcRenderer.invoke('shell:openFolder', p),
  twitchStatus: () => ipcRenderer.invoke('twitch:status'),
  twitchLogin: () => ipcRenderer.invoke('twitch:login'),
  twitchCancelLogin: () => ipcRenderer.invoke('twitch:cancelLogin'),
  twitchLogout: () => ipcRenderer.invoke('twitch:logout'),
  twitchVideos: () => ipcRenderer.invoke('twitch:videos'),
  onTwitchStatus: on('twitch:status'),
  onTwitchEvent: on('twitch:event'),
  obsCurrent: () => ipcRenderer.invoke('obs:current'),
  precheck: () => ipcRenderer.invoke('precheck:run'),
  onObsStatus: on('obs:status'),
  onObsState: on('obs:state'),
  onObsEvent: on('obs:event'),
  onObsError: on('obs:error'),
  onEngineProgress: on('engine:progress'),
  friendsStatus: () => ipcRenderer.invoke('friends:status'),
  friendsForClip: (folder, clip) => ipcRenderer.invoke('friends:forClip', folder, clip),
  friendsPending: () => ipcRenderer.invoke('friends:pending'),
  friendsAccept: (id) => ipcRenderer.invoke('friends:accept', id),
  friendsRefuse: (id) => ipcRenderer.invoke('friends:refuse', id),
  friendsRequest: (folder, clip, to) => ipcRenderer.invoke('friends:request', folder, clip, to),
  friendsCheck: () => ipcRenderer.invoke('friends:check'),
  onFriendsEvent: on('friends:event'),
});
